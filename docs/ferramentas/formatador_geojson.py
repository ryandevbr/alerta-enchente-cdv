# 3. MOTOR DE COMPRESSÃO

def formatar_geojson(texto_json, cota):
    try:
        # Lê o texto colado e transforma em objeto Python
        dados = json.loads(texto_json.strip())
    except json.JSONDecodeError:
        print(" Erro: O texto colado não é um JSON válido. Copiou tudo?")
        return

    # Descobre se o site gerou uma coleção de polígonos ou apenas um
    features = dados.get('features', [dados]) if 'type' in dados and dados['type'] == 'FeatureCollection' else [dados]
    
    resultados = []
    
    for feat in features:
        if 'geometry' not in feat:
            continue
            
        tipo_geometria = feat['geometry']['type']
        
        # Comprime a escadinha de coordenadas em uma única linha
        coords_compactas = json.dumps(feat['geometry']['coordinates'], separators=(', ', ': '))
        
        # Monta a estrutura final
        bloco_formatado = (
            '{\n'
            '    "type": "Feature",\n'
            f'    "properties": {{ "cota": {cota} }},\n'
            '    "geometry": {\n'
            f'        "type": "{tipo_geometria}",\n'
            f'        "coordinates": {coords_compactas}\n'
            '    }\n'
            '}'
        )
        resultados.append(bloco_formatado)
        
    texto_final = ",\n".join(resultados)
    
    print("\n" + "="*50)
    print(" SCRIPT LIMPO! SÓ COPIAR E COLAR NO INDEX.HTML:")
    print("="*50 + "\n")
    print(texto_final)
    print("\n" + "="*50)

if __name__ == "__main__":
    if JSON_BRUTO.strip():
        formatar_geojson(JSON_BRUTO, COTA)
